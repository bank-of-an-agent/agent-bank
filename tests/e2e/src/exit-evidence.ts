import { formatAmount } from "@agentbank/core";
import { arch, cpus, platform } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { ExitResult } from "./exit";
import { writeEvidenceFile } from "./write-evidence";

export const PHASE5_EVIDENCE = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../../docs/gates/evidence/phase-5-exit-drill.md",
);

const usd = (minor: bigint): string => `$${formatAmount(minor, 6)}`;

export interface ExitDrillEvidence {
  result: ExitResult;
  funded: bigint;
  float: bigint;
  recoverable: bigint;
  leftBehind: bigint;
  streamedAway: bigint;
  feesToRevenue: bigint;
  suspenseAfterRestart: bigint;
  mismatchEvents: number;
  agentPaused: boolean;
  runtimeMs: number;
}

export function writePhase5Evidence(e: ExitDrillEvidence): void {
  const lines: string[] = [];
  lines.push("# Phase 5 gate evidence: owner exit drill");
  lines.push("");
  lines.push(
    "Gate criterion (design § Implementation plan, Phase 5): the **owner exit tool published and tested against a simulated bank shutdown**. This drill is the simulated-chain counterpart of the standalone exit tool's Anvil shutdown drill ([`bank-of-an-agent/exit-tool`](https://github.com/bank-of-an-agent/exit-tool/blob/main/docs/shutdown-drill.md)).",
  );
  lines.push("");
  const pass = e.leftBehind === 0n && e.result.recovered === e.recoverable;
  lines.push(
    `**Result: ${pass ? "PASS" : "FAIL"}.** With the API, co-signer, facilitator and indexer stopped, the owner recovered ${usd(e.result.recovered)} to a cold wallet using only the owner key and the chain, leaving ${usd(e.leftBehind)} behind. When services restarted, reconciliation flagged the owner-initiated movements as unexplained: ${usd(e.suspenseAfterRestart)} in \`sys:suspense\`, ${e.mismatchEvents} \`reconciliation.mismatch\` event(s), and the agent paused (${e.agentPaused ? "yes" : "no"}).`,
  );
  lines.push("");
  lines.push(
    "The account was funded and given an escrow, a stream and a time-locked vault position plus a spend-key float. The exit uses the Safe-native `execTransaction` (which bypasses the ERC-7579 modules and the policy hook) for the account's own calls, and the permissionless exit paths for the rest, exactly as the exit tool does. Generated by `tests/e2e/test/exit-drill.test.ts`; reproduce with `pnpm --filter @agentbank/e2e gate:phase5`.",
  );
  lines.push("");
  lines.push(
    `Runtime ${(e.runtimeMs / 1000).toFixed(1)} s on ${platform()} ${arch()}, ${cpus().length} CPUs. Simulated chain.`,
  );
  lines.push("");

  lines.push("## Funds");
  lines.push("");
  lines.push("| Quantity | Value |");
  lines.push("| --- | ---: |");
  lines.push(`| Funded (operating) | ${usd(e.funded)} |`);
  lines.push(`| Spend-key float | ${usd(e.float)} |`);
  lines.push(`| Fees paid to revenue (escrow 1%, stream 0.5%) | ${usd(e.feesToRevenue)} |`);
  lines.push(`| Streamed to the payee before the exit (not recoverable) | ${usd(e.streamedAway)} |`);
  lines.push(`| **Recoverable** | **${usd(e.recoverable)}** |`);
  lines.push(`| **Recovered to the owner's cold wallet** | **${usd(e.result.recovered)}** |`);
  lines.push(`| Left behind | ${usd(e.leftBehind)} |`);
  lines.push("");

  lines.push("## Exit steps (owner key + chain only)");
  lines.push("");
  lines.push("| Step | Detail |");
  lines.push("| --- | --- |");
  for (const s of e.result.steps) lines.push(`| \`${s.step}\` | ${s.detail} |`);
  lines.push("");

  lines.push("## After restart");
  lines.push("");
  lines.push(
    "The indexer and reconciler came back up against the same chain and ledger. Every owner-initiated outflow matched no payment record, so the reconciler posted it to `sys:suspense`, emitted a `reconciliation.mismatch` event and paused the agent's sessions — the behaviour the reconciliation-mismatch runbook describes for an owner exit. Chain and ledger stay true to each other: the loss of meaning is recorded, not hidden.",
  );
  lines.push("");

  writeEvidenceFile(PHASE5_EVIDENCE, lines.join("\n") + "\n");
}
