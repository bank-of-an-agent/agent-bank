import { arch, cpus, platform } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { ProofRoot } from "@agentbank/sdk";
import type { ProofStats } from "./proofs";
import { writeEvidenceFile } from "./write-evidence";

/** Where the private-proofs evidence is written (only by `gate:proofs`, never by CI `test`). */
export const PRIVATE_PROOFS_EVIDENCE = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../../docs/gates/evidence/private-proofs.md",
);

/** The scenarios the suite must complete, in order (ids as in `stats.scenario`). */
const EXPECTED_SCENARIOS = 9;

const ms = (value: number): string => `${value < 100 ? value.toFixed(1) : Math.round(value)} ms`;

function quantile(sorted: readonly number[], q: number): number {
  if (sorted.length === 0) return Number.NaN;
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil(q * sorted.length) - 1));
  return sorted[index] as number;
}

function timingRow(label: string, values: readonly number[]): string {
  if (values.length === 0) return `| ${label} | 0 | – | – | – | – |`;
  const sorted = [...values].sort((a, b) => a - b);
  return `| ${label} | ${sorted.length} | ${ms(sorted[0] as number)} | ${ms(quantile(sorted, 0.5))} | ${ms(quantile(sorted, 0.95))} | ${ms(sorted.at(-1) as number)} |`;
}

const total = (map: Map<string, number>): number => [...map.values()].reduce((a, b) => a + b, 0);
const sortedEntries = (map: Map<string, number>) =>
  [...map.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

export interface PrivateProofsEvidenceMeta {
  runtimeMs: number;
  /** Every root the run built (`GET /v1/proofs/roots`). */
  roots: readonly ProofRoot[];
  /** How many of them the registry reports as revoked. */
  revokedOnChain: number;
  /** The circuit's constraint count (`GET /v1/proofs/circuit`). */
  constraints: number;
  /** The sellers' default `min_anonymity_set`. */
  minAnonymitySet: number;
}

export function writePrivateProofsEvidence(stats: ProofStats, meta: PrivateProofsEvidenceMeta): void {
  const rootsByStatus = new Map<string, number>();
  for (const root of meta.roots) rootsByStatus.set(root.status, (rootsByStatus.get(root.status) ?? 0) + 1);
  const revoked = rootsByStatus.get("revoked") ?? 0;
  const verifierRefused = total(stats.verifierRefusals);
  const agentRefused = total(stats.agentRefusals);
  const witnessRefused = total(stats.witnessRefusals);
  const pass =
    stats.scenarios.length === EXPECTED_SCENARIOS &&
    revoked > 0 &&
    meta.revokedOnChain === revoked &&
    (rootsByStatus.get("failed") ?? 0) === 0;
  const sets = [...stats.anonymitySets].sort((a, b) => a - b);
  const gateSets = [...stats.gateMinAnonymitySets].sort((a, b) => a - b);

  const lines: string[] = [];
  lines.push("# Private proofs evidence: end to end");
  lines.push("");
  lines.push(
    "What it shows ([design](../../private-proofs.md), ADR 0014): agents prove **agent credentials**, **private reputation** and **proof of funds / reservations** to sellers with real Groth16 proofs, without revealing which agent they are; owners control what may be disclosed, and narrowing, freezing and early releases revoke roots at once.",
  );
  lines.push("");
  lines.push(
    `**Result: ${pass ? "PASS" : "FAIL"}.** ${stats.scenarios.length} of ${EXPECTED_SCENARIOS} scenarios ran end to end. ${stats.generated} proofs generated, ${stats.accepted} presentations accepted by the sellers' gates, ${verifierRefused} refused by the gates and ${agentRefused} requests refused by the agent's own SDK before proving. ${meta.roots.length} roots built, ${revoked} revoked (${meta.revokedOnChain} revoked in the registry on-chain), ${rootsByStatus.get("failed") ?? 0} failed.`,
  );
  lines.push("");
  lines.push(
    "The whole stack runs in one process over real HTTP (API, co-signer, reconciler, indexer, x402 facilitator, the real `proofs-roots` and `proofs-reservations` jobs) on the simulated chain, whose `AgentAttestationRegistry` anchors every root. Agents use the TypeScript SDK (`agent.proofs`, `fetchWithPayment`), owners the `PrincipalClient`, and two sellers admit agents with `@agentbank/sdk/proof-server` gates that resolve roots through `GET /v1/proofs/roots/{root}`. Generated by `tests/e2e/test/private-proofs.test.ts`; reproduce with `pnpm --filter @agentbank/e2e gate:proofs` (this file is rewritten only then; CI's `pnpm test` runs the same suite with fewer timing runs).",
  );
  lines.push("");
  lines.push(
    `Runtime ${(meta.runtimeMs / 1000).toFixed(1)} s on ${platform()} ${arch()}, ${cpus().length} CPUs. Circuit \`agent_claims\`: ${meta.constraints.toLocaleString("en-US")} constraints, Groth16 on BN254, keys from the single-party testnet-only setup.`,
  );
  lines.push("");

  lines.push("## Scenarios");
  lines.push("");
  lines.push("| | Scenario | Checked |");
  lines.push("| --- | --- | --- |");
  for (const s of stats.scenarios) lines.push(`| ${s.id} | ${s.title} | ${s.detail} |`);
  lines.push("");

  lines.push("## Proofs");
  lines.push("");
  lines.push("| Quantity | Count |");
  lines.push("| --- | ---: |");
  lines.push(`| Proofs generated (real prover, witness from the API) | ${stats.generated} |`);
  lines.push(`| Gate checks of a presentation | ${stats.verifyingMs.length} |`);
  lines.push(`| Accepted | ${stats.accepted} |`);
  lines.push(`| Refused by a gate | ${verifierRefused} |`);
  lines.push(`| Challenges issued (401 without a presentation) | ${stats.challenges} |`);
  lines.push(`| Refused by the agent's SDK, nothing proved or sent | ${agentRefused} |`);
  lines.push(`| Witness refused by Agent Bank | ${witnessRefused} |`);
  lines.push("");
  lines.push(
    "A priced resource checks the same presentation twice (before the 402, without using it up, and on the paid retry), so accepted checks can exceed proofs; refused presentations include ones prepared before a revocation and replays.",
  );
  lines.push("");
  lines.push("### Refusals by reason");
  lines.push("");
  lines.push("| Refused by | Reason | Count |");
  lines.push("| --- | --- | ---: |");
  for (const [reason, n] of sortedEntries(stats.verifierRefusals))
    lines.push(`| Seller's gate | \`${reason}\` | ${n} |`);
  for (const [reason, n] of sortedEntries(stats.agentRefusals))
    lines.push(`| Agent's SDK | \`${reason}\` | ${n} |`);
  for (const [reason, n] of sortedEntries(stats.witnessRefusals))
    lines.push(`| Agent Bank (witness) | \`${reason}\` | ${n} |`);
  lines.push("");
  lines.push("### `POST /v1/proofs/verify`");
  lines.push("");
  lines.push("| Outcome | Count |");
  lines.push("| --- | ---: |");
  for (const [outcome, n] of sortedEntries(stats.apiVerifications)) lines.push(`| \`${outcome}\` | ${n} |`);
  lines.push("");

  lines.push("## Timings");
  lines.push("");
  lines.push("| Step | n | Min | Median | p95 | Max |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: |");
  lines.push(timingRow("Proving (Groth16, witness in hand)", stats.provingMs));
  lines.push(timingRow("Gate check (root lookup over HTTP + Groth16 verify)", stats.verifyingMs));
  lines.push("");
  lines.push(
    "Proving runs in the test process alongside the whole stack, so it is slower than on an idle machine (the design quotes about 1.3 s); refused gate checks that stop before the pairing check (nonce, root) are the fast tail.",
  );
  lines.push("");

  lines.push("## Anonymity sets");
  lines.push("");
  lines.push("| Quantity | Value |");
  lines.push("| --- | ---: |");
  lines.push(
    `| Leaves of the roots proved against (min – max) | ${sets.length > 0 ? `${sets[0]} – ${sets.at(-1)}` : "–"} |`,
  );
  lines.push(`| Distinct roots proved against | ${stats.rootsProvedAgainst.size} |`);
  lines.push(`| Sellers' default \`min_anonymity_set\` | ${meta.minAnonymitySet} |`);
  lines.push(`| \`min_anonymity_set\` values requested | ${gateSets.join(", ")} |`);
  lines.push("");
  lines.push(
    `The stack has a handful of agents, so the sellers lower \`min_anonymity_set\` to ${meta.minAnonymitySet} (the SDK default, and the bar for real deployments, is 16). The boundary scenario asks for exactly the tree's leaf count (accepted) and one more (\`anonymity_set_too_small\`).`,
  );
  lines.push("");

  lines.push("## Roots and reservations");
  lines.push("");
  lines.push("| Quantity | Count |");
  lines.push("| --- | ---: |");
  lines.push(`| Roots built by \`proofs-roots\` | ${meta.roots.length} |`);
  for (const status of ["published", "revoked", "expired", "failed", "publishing"]) {
    const n = rootsByStatus.get(status) ?? 0;
    if (n > 0 || status === "revoked" || status === "failed") lines.push(`| … ${status} at the end | ${n} |`);
  }
  lines.push(`| Revoked in the registry (\`rootInfo.revoked\`) | ${meta.revokedOnChain} |`);
  lines.push(`| Reservations created | ${stats.reservations.created} |`);
  lines.push(`| … released early by the owner | ${stats.reservations.released} |`);
  lines.push(`| … expired (hold voided) | ${stats.reservations.expired} |`);
  lines.push("");
  lines.push(
    "Roots are revoked by narrowing changes only: removing a disclosure class, freezing an agent and an owner's early release each publish a new root and revoke every older root still valid, in the API and on-chain.",
  );
  lines.push("");

  writeEvidenceFile(PRIVATE_PROOFS_EVIDENCE, lines.join("\n") + "\n");
}
